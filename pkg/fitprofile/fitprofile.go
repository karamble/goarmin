// Package fitprofile names everything in a FIT file a Garmin device may write: the messages
// and their fields (number, name, base type, type, units, scale, offset), the enumerations,
// the file types and the devices.
//
// The official messages and fields are Garmin's FIT profile. The messages and fields Garmin
// does not document (ECG, skin temperature, solar charge, sleep disruption, …), the
// enumerations, the file types beyond the official ones and the device names come from the
// community's description of the format (Gadgetbridge's). Official is false for those.
//
// The tables are generated by tools/fitprofilegen (make fitprofile).
package fitprofile

import (
	"sort"
	"strconv"
	"sync"
)

// Message is a FIT message.
type Message struct {
	Num      uint16
	Name     string
	Official bool // in Garmin's published profile
	Fields   []Field
}

// Field is a field of a message.
type Field struct {
	Num      uint8
	Name     string
	Base     string // the base type: uint8, sint32, string, enum, …
	Type     string // the profile type: date_time, sport, sleep_level, … (the base type when there is none)
	Units    string
	Scale    float64 // 0 or 1: none
	Offset   float64
	Array    bool
	ArrayLen int // a fixed length the community profile gives, 0 if none
	Official bool
}

// Value turns a stored value into the field's unit: divided by the scale, less the offset.
func (f Field) Value(raw float64) float64 {
	s := f.Scale
	if s == 0 {
		s = 1
	}
	return raw/s - f.Offset
}

// Enum is an enumeration fields refer to by Type.
type Enum struct {
	Name    string
	Entries []Entry
}

// Entry is one value of an enumeration.
type Entry struct {
	Num  uint32
	Name string
}

// FileType is a FIT file's type (file_id.type).
type FileType struct {
	Num      uint8
	Name     string
	Title    string // in words, for people
	Official bool
	Archive  bool // devices let a host mark these as synced (they are records, not settings)
}

// OtherFile is a file a Garmin device keeps that is not FIT (an XML document, a crash report),
// by its data type and subtype in the device's file list.
type OtherFile struct {
	Type, Subtype uint8
	Name          string
}

// Device is a product a manufacturer's FIT files name.
type Device struct {
	Manufacturer, Product uint16
	Name                  string
}

// Messages lists every known message by number.
func Messages() []Message { return messages }

// Lookup finds a message by number.
func Lookup(num uint16) (Message, bool) {
	i := sort.Search(len(messages), func(i int) bool { return messages[i].Num >= num })
	if i < len(messages) && messages[i].Num == num {
		return messages[i], true
	}
	return Message{}, false
}

// MessageName names a message; an unknown one is "message_<num>".
func MessageName(num uint16) string {
	if m, ok := Lookup(num); ok {
		return m.Name
	}
	return "message_" + strconv.Itoa(int(num))
}

// Field finds a field of the message by number.
func (m Message) Field(num uint8) (Field, bool) {
	i := sort.Search(len(m.Fields), func(i int) bool { return m.Fields[i].Num >= num })
	if i < len(m.Fields) && m.Fields[i].Num == num {
		return m.Fields[i], true
	}
	return Field{}, false
}

// FieldName names a field of a message; an unknown one is "field_<num>".
func FieldName(msg uint16, field uint8) string {
	if m, ok := Lookup(msg); ok {
		if f, ok := m.Field(field); ok {
			return f.Name
		}
	}
	return "field_" + strconv.Itoa(int(field))
}

var enumIndex = sync.OnceValue(func() map[string]Enum {
	m := make(map[string]Enum, len(enums))
	for _, e := range enums {
		m[e.Name] = e
	}
	return m
})

// Enums lists every known enumeration by name.
func Enums() []Enum { return enums }

// LookupEnum finds an enumeration by name ("sleep_level").
func LookupEnum(name string) (Enum, bool) {
	e, ok := enumIndex()[name]
	return e, ok
}

// Value names an enumeration's value ("" if unknown).
func (e Enum) Value(v uint32) string {
	i := sort.Search(len(e.Entries), func(i int) bool { return e.Entries[i].Num >= v })
	if i < len(e.Entries) && e.Entries[i].Num == v {
		return e.Entries[i].Name
	}
	return ""
}

// EnumValue names a value of the enumeration called name ("" if either is unknown).
func EnumValue(name string, v uint32) string {
	if e, ok := LookupEnum(name); ok {
		return e.Value(v)
	}
	return ""
}

// FileTypes lists every known FIT file type by number.
func FileTypes() []FileType { return fileTypes }

// LookupFileType finds a FIT file type by number.
func LookupFileType(t uint8) (FileType, bool) {
	i := sort.Search(len(fileTypes), func(i int) bool { return fileTypes[i].Num >= t })
	if i < len(fileTypes) && fileTypes[i].Num == t {
		return fileTypes[i], true
	}
	return FileType{}, false
}

// FileTypeName names a FIT file type ("skin_temp"); an unknown one is "file_type_<num>".
func FileTypeName(t uint8) string {
	if ft, ok := LookupFileType(t); ok {
		return ft.Name
	}
	return "file_type_" + strconv.Itoa(int(t))
}

// FileTypeTitle is a FIT file type in words ("Skin temperature"); an unknown one is "Type <num>".
func FileTypeTitle(t uint8) string {
	if ft, ok := LookupFileType(t); ok {
		return ft.Title
	}
	return "Type " + strconv.Itoa(int(t))
}

// OtherFiles lists the known files that are not FIT.
func OtherFiles() []OtherFile { return otherFiles }

// OtherFileName names a non-FIT file by its data type and subtype ("" if unknown).
func OtherFileName(typ, sub uint8) string {
	for _, o := range otherFiles {
		if o.Type == typ && o.Subtype == sub {
			return o.Name
		}
	}
	return ""
}

// Devices lists the known products by manufacturer and product number.
func Devices() []Device { return devices }

// DeviceName names a manufacturer's product ("" if unknown).
func DeviceName(manufacturer, product uint16) string {
	i := sort.Search(len(devices), func(i int) bool {
		d := devices[i]
		return d.Manufacturer > manufacturer || (d.Manufacturer == manufacturer && d.Product >= product)
	})
	if i < len(devices) && devices[i].Manufacturer == manufacturer && devices[i].Product == product {
		return devices[i].Name
	}
	return ""
}
